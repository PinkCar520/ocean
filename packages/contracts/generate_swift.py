from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
SCHEMA_PATH = ROOT / "packages/contracts/schemas/domain.schema.json"
# Contracts were promoted to the monorepo root (shared by Ocean and OLO).
# The generated Swift file still lives inside the OLO product tree.
OUTPUT_PATH = (
    ROOT
    / "products/olo/OLO/Core/ControlPlane/OLOControlPlaneContracts.generated.swift"
)


def swift_type(schema: dict[str, Any], definitions: dict[str, Any]) -> str:
    if reference := schema.get("$ref"):
        key = reference.rsplit("/", 1)[-1]
        return definitions[key]["x-swift-name"]

    raw_type = schema.get("type")
    nullable = isinstance(raw_type, list) and "null" in raw_type
    base_type = next(item for item in raw_type if item != "null") if nullable else raw_type
    if base_type == "string":
        result = "Date" if schema.get("format") == "date-time" else "String"
    elif base_type == "integer" or "const" in schema:
        result = "Int"
    elif base_type == "number":
        result = "Double"
    elif base_type == "boolean":
        result = "Bool"
    elif base_type == "object" and schema.get("additionalProperties", {}).get("type") == "string":
        result = "[String: String]"
    else:
        raise ValueError(f"unsupported contract schema: {schema}")
    return f"{result}?" if nullable else result


def render(schema: dict[str, Any]) -> str:
    definitions = schema["$defs"]
    blocks = [
        "// Generated by packages/contracts/generate_swift.py.",
        "// Source: packages/contracts/schemas/domain.schema.json.",
        "// Do not edit this file by hand.",
        "",
        "import Foundation",
    ]
    for key in schema["x-swift-order"]:
        definition = definitions[key]
        name = definition["x-swift-name"]
        if "enum" in definition:
            cases = definition.get("x-swift-cases", {})
            lines = [f"enum {name}: String, Codable, Sendable {{"]
            for value in definition["enum"]:
                case_name = cases.get(value, value)
                suffix = f' = "{value}"' if case_name != value else ""
                lines.append(f"    case {case_name}{suffix}")
            lines.append("}")
        else:
            required = set(definition.get("required", []))
            lines = [f"struct {name}: Codable, Sendable, Hashable {{"]
            for property_name, property_schema in definition["properties"].items():
                property_type = swift_type(property_schema, definitions)
                if property_name not in required and not property_type.endswith("?"):
                    property_type += "?"
                lines.append(f"    let {property_name}: {property_type}")
            lines.append("}")
        blocks.extend(["", *lines])
    return "\n".join(blocks) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate OLO Swift domain contracts")
    parser.add_argument("--check", action="store_true", help="fail when committed output is stale")
    arguments = parser.parse_args()
    output = render(json.loads(SCHEMA_PATH.read_text()))
    if arguments.check:
        if not OUTPUT_PATH.exists() or OUTPUT_PATH.read_text() != output:
            raise SystemExit("generated Swift contracts are stale")
        return 0
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(output)
    print(OUTPUT_PATH.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
